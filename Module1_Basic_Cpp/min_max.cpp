// min() and max() Built-in function in C++
#include<bits/stdc++.h>
using namespace std;
int main() {
    int a = 10, b = 20;
    cout << "Minimum of " << a << " and " << b << " is: " << min(a, b) << endl;
    cout << "Maximum of " << a << " and " << b << " is: " << max(a, b) << endl; 
    return 0;
}